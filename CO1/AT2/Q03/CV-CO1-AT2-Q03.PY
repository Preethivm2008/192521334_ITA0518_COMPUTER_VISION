import cv2
import numpy as np
import matplotlib.pyplot as plt

# Create a black background
height, width = 400, 600
frame1 = np.zeros((height, width, 3), dtype=np.uint8)
frame2 = np.zeros((height, width, 3), dtype=np.uint8)

# Draw a moving object (white rectangle)
cv2.rectangle(frame1, (150,150), (220,220), (255,255,255), -1)
cv2.rectangle(frame2, (220,150), (290,220), (255,255,255), -1)

# Convert to grayscale
gray1 = cv2.cvtColor(frame1, cv2.COLOR_BGR2GRAY)
gray2 = cv2.cvtColor(frame2, cv2.COLOR_BGR2GRAY)

# Detect motion using frame difference
diff = cv2.absdiff(gray1, gray2)

# Threshold
_, thresh = cv2.threshold(diff, 30, 255, cv2.THRESH_BINARY)

# Find contours
contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

# Draw bounding boxes
result = frame2.copy()

for cnt in contours:
    if cv2.contourArea(cnt) > 100:
        x, y, w, h = cv2.boundingRect(cnt)
        cv2.rectangle(result, (x, y), (x+w, y+h), (0,255,0), 2)
        cv2.putText(result, "Object Detected",
                    (x, y-10),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.5,
                    (0,255,0),
                    2)

# Display results
titles = ["Frame 1", "Frame 2", "Motion Detection", "Surveillance Output"]
images = [gray1, gray2, thresh, cv2.cvtColor(result, cv2.COLOR_BGR2RGB)]

plt.figure(figsize=(14,5))

for i in range(4):
    plt.subplot(1,4,i+1)
    if i < 3:
        plt.imshow(images[i], cmap='gray')
    else:
        plt.imshow(images[i])
    plt.title(titles[i])
    plt.axis("off")

plt.show()

print("Computer Vision Surveillance Features Demonstrated:")
print("✔ Image Acquisition")
print("✔ Motion Detection")
print("✔ Object Detection")
print("✔ Object Localization (Bounding Box)")
print("✔ Real-Time Surveillance Concept")
