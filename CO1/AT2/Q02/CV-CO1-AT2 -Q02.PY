import cv2
import numpy as np
import matplotlib.pyplot as plt
from skimage import data

# Load sample image
image = data.astronaut()
image = cv2.cvtColor(image, cv2.COLOR_RGB2GRAY)

# -----------------------------
# Simulate Improper Image Formation
# -----------------------------

# 1. Blur (Out-of-focus lens)
blurred = cv2.GaussianBlur(image, (11,11), 5)

# 2. Add Gaussian Noise (Sensor Noise)
noise = np.random.normal(0, 20, blurred.shape).astype(np.int16)
noisy = np.clip(blurred.astype(np.int16) + noise, 0, 255).astype(np.uint8)

# 3. Reduce Contrast (Poor Illumination)
low_contrast = cv2.convertScaleAbs(noisy, alpha=0.6, beta=20)

# -----------------------------
# Image Improvement
# -----------------------------

# Histogram Equalization
equalized = cv2.equalizeHist(low_contrast)

# Denoising
denoised = cv2.fastNlMeansDenoising(equalized, None, 10, 7, 21)

# Sharpening
kernel = np.array([[0,-1,0],
                   [-1,5,-1],
                   [0,-1,0]])
sharpened = cv2.filter2D(denoised, -1, kernel)

# -----------------------------
# Display Images
# -----------------------------
titles = ["Original",
          "Distorted",
          "Histogram Equalized",
          "Final Improved"]

images = [image,
          low_contrast,
          equalized,
          sharpened]

plt.figure(figsize=(15,5))

for i in range(4):
    plt.subplot(1,4,i+1)
    plt.imshow(images[i], cmap='gray')
    plt.title(titles[i])
    plt.axis('off')

plt.show()

# -----------------------------
# Result
# -----------------------------
print("Possible Causes of Distortion:")
print("1. Lens Blur")
print("2. Sensor Noise")
print("3. Poor Illumination (Low Contrast)")
print("4. Improper Focus")

print("\nSuggested Improvements:")
print("✔ Histogram Equalization - Improves Contrast")
print("✔ Denoising Filter - Removes Noise")
print("✔ Sharpening Filter - Enhances Edges")
