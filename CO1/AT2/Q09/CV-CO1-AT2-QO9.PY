import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# Upload a road image
print("Upload a road image")
uploaded = files.upload()

# Read image
image_path = list(uploaded.keys())[0]
image = cv2.imread(image_path)

# Convert BGR to RGB
original = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

# Convert to Grayscale
gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

# Reduce Noise
blur = cv2.GaussianBlur(gray, (5,5), 0)

# Edge Detection
edges = cv2.Canny(blur, 50, 150)

# Detect Lane Lines
lines = cv2.HoughLinesP(edges,
                        rho=1,
                        theta=np.pi/180,
                        threshold=80,
                        minLineLength=50,
                        maxLineGap=10)

lane_image = original.copy()

if lines is not None:
    for line in lines:
        x1, y1, x2, y2 = line[0]
        cv2.line(lane_image, (x1,y1), (x2,y2), (255,0,0), 3)

# Display Images
titles = [
    "Original Road Image",
    "Grayscale",
    "Edge Detection",
    "Detected Lane Lines"
]

images = [original, gray, edges, lane_image]

plt.figure(figsize=(12,8))

for i in range(4):
    plt.subplot(2,2,i+1)
    if len(images[i].shape)==2:
        plt.imshow(images[i], cmap='gray')
    else:
        plt.imshow(images[i])
    plt.title(titles[i])
    plt.axis('off')

plt.tight_layout()
plt.show()

# Display Information
print("\n========== COMPUTER VISION OUTPUT ==========")
print("Image Acquisition      : Successful")
print("Noise Reduction        : Applied")
print("Edge Detection         : Completed")
print("Lane Detection         :", "Successful" if lines is not None else "No lanes detected")

print("\nObservation:")
print("- Clear image acquisition improves detection accuracy.")
print("- Edge detection identifies road boundaries.")
print("- Lane detection helps the vehicle remain in its lane.")
print("- Reliable Computer Vision improves driving decisions.")
