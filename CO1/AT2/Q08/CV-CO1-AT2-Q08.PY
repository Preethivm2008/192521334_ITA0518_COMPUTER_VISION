# ==========================================
# Medical Image Quantization Demonstration
# Google Colab Compatible
# ==========================================

import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# Upload a medical image (X-ray, MRI, CT, etc.)
print("Upload a medical image")
uploaded = files.upload()

# Read the uploaded image
image_path = list(uploaded.keys())[0]
image = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)

# Convert to 256-level image (Original)
original = image

# Proper Quantization (64 Gray Levels)
quant_64 = (original // 4) * 4

# Improper Quantization (8 Gray Levels)
quant_8 = (original // 32) * 32

# Display Images
titles = [
    "Original (256 Gray Levels)",
    "Proper Quantization (64 Levels)",
    "Improper Quantization (8 Levels)"
]

images = [original, quant_64, quant_8]

plt.figure(figsize=(15,5))

for i in range(3):
    plt.subplot(1,3,i+1)
    plt.imshow(images[i], cmap='gray')
    plt.title(titles[i])
    plt.axis('off')

plt.tight_layout()
plt.show()

# Print Information
print("\n========== IMAGE INFORMATION ==========")
print("Original Shape :", original.shape)
print("Original Gray Levels : 256")
print("Proper Quantization : 64 Gray Levels")
print("Improper Quantization : 8 Gray Levels")

print("\nObservation:")
print("- Proper quantization preserves most diagnostic details.")
print("- Improper quantization removes subtle intensity differences.")
print("- Fine structures and tissue boundaries become difficult to observe.")
print("- This may reduce diagnostic accuracy.")
