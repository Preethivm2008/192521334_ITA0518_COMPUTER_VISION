# ==========================================
# Fine Detail Detection using Sampling and Intensity Resolution
# Google Colab Compatible
# ==========================================

import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# Upload an image
print("Upload a high-detail image")
uploaded = files.upload()

# Read image in grayscale
image_path = list(uploaded.keys())[0]
original = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)

# -------------------------------
# High Sampling (Original)
# -------------------------------
high_sampling = original.copy()

# -------------------------------
# Low Sampling (Reduce Resolution)
# -------------------------------
low_sampling = cv2.resize(original, (0,0), fx=0.5, fy=0.5)
low_sampling = cv2.resize(low_sampling,
                          (original.shape[1], original.shape[0]),
                          interpolation=cv2.INTER_NEAREST)

# -------------------------------
# High Intensity Resolution
# (256 Gray Levels)
# -------------------------------
high_intensity = original.copy()

# -------------------------------
# Low Intensity Resolution
# (16 Gray Levels)
# -------------------------------
low_intensity = (original // 16) * 16

# -------------------------------
# Display Images
# -------------------------------
titles = [
    "Original (High Sampling)",
    "Low Sampling",
    "High Intensity (256 Levels)",
    "Low Intensity (16 Levels)"
]

images = [
    high_sampling,
    low_sampling,
    high_intensity,
    low_intensity
]

plt.figure(figsize=(12,8))

for i in range(4):
    plt.subplot(2,2,i+1)
    plt.imshow(images[i], cmap='gray')
    plt.title(titles[i])
    plt.axis('off')

plt.tight_layout()
plt.show()

# -------------------------------
# Image Information
# -------------------------------
print("\n========== IMAGE ANALYSIS ==========")
print("Original Resolution :", original.shape)
print("Low Sampling Resolution :", low_sampling.shape)
print("Intensity Resolution (Original): 256 Gray Levels")
print("Intensity Resolution (Reduced): 16 Gray Levels")

print("\nObservation:")
print("- High sampling preserves fine edges and textures.")
print("- Low sampling removes small image details.")
print("- High intensity resolution preserves smooth intensity variations.")
print("- Low intensity resolution causes loss of subtle image information.")
print("- For fine-detail detection, choose high sampling and high intensity resolution.")
