# ==========================================
# Sampling and Quantization Demonstration
# Google Colab Compatible
# ==========================================

import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# Upload an image
print("Upload a high-resolution image")
uploaded = files.upload()

# Read image
image_path = list(uploaded.keys())[0]
image = cv2.imread(image_path)

# Convert BGR to RGB
original = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

# ------------------------------------------
# Sampling: Reduce Image Resolution
# ------------------------------------------
sampled = cv2.resize(original, (0,0), fx=0.5, fy=0.5)

# ------------------------------------------
# Quantization: Reduce Gray Levels
# ------------------------------------------
gray = cv2.cvtColor(original, cv2.COLOR_RGB2GRAY)

# Reduce to 16 gray levels
quantized = (gray // 16) * 16

# ------------------------------------------
# Display Images
# ------------------------------------------
titles = ['Original Image',
          'Sampled Image (50% Resolution)',
          'Grayscale Image',
          'Quantized Image (16 Levels)']

images = [original, sampled, gray, quantized]

plt.figure(figsize=(12,8))

for i in range(4):
    plt.subplot(2,2,i+1)
    if len(images[i].shape)==2:
        plt.imshow(images[i], cmap='gray')
    else:
        plt.imshow(images[i])
    plt.title(titles[i])
    plt.axis('off')

plt.tight_layout()
plt.show()

# ------------------------------------------
# Compare Storage Size
# ------------------------------------------
print("\nImage Information")
print("------------------------------")

print("Original Resolution :", original.shape)
print("Sampled Resolution  :", sampled.shape)

original_size = original.nbytes
sampled_size = sampled.nbytes
quantized_size = quantized.nbytes

print("\nApproximate Memory Usage")
print("Original Image   :", original_size/1024, "KB")
print("Sampled Image    :", sampled_size/1024, "KB")
print("Quantized Image  :", quantized_size/1024, "KB")

print("\nProcessing Completed Successfully!")
