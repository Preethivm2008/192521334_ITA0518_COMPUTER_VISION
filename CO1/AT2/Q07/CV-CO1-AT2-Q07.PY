# ==========================================
# Image Contrast Enhancement under Uneven Lighting
# Google Colab Compatible
# ==========================================

import cv2
import matplotlib.pyplot as plt
from google.colab import files

# Upload an image
print("Upload an image captured under uneven lighting")
uploaded = files.upload()

# Read the uploaded image
image_path = list(uploaded.keys())[0]
image = cv2.imread(image_path)

# Convert BGR to RGB
original = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

# Convert to Grayscale
gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

# Histogram Equalization
hist_eq = cv2.equalizeHist(gray)

# CLAHE (Adaptive Histogram Equalization)
clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
clahe_img = clahe.apply(gray)

# Display Results
titles = [
    "Original Image",
    "Grayscale",
    "Histogram Equalization",
    "CLAHE (Improved Contrast)"
]

images = [original, gray, hist_eq, clahe_img]

plt.figure(figsize=(12,8))

for i in range(4):
    plt.subplot(2,2,i+1)
    if len(images[i].shape) == 2:
        plt.imshow(images[i], cmap='gray')
    else:
        plt.imshow(images[i])
    plt.title(titles[i])
    plt.axis("off")

plt.tight_layout()
plt.show()

print("Contrast Enhancement Completed Successfully!")
